"""
Metadata evidence stream.

This module reads EXIF/XMP via ExifTool and derives *heuristic* feature
flags. Every finding here is unverified — a string in an EXIF field, a
provenance-related tag name, or a binary marker in the file bytes. The
heuristic score treats these as weak evidence only.

For anything that needs to distinguish "the file contains the substring
``c2pa``" from "this image carries a cryptographically valid C2PA
manifest saying it is AI-generated", use
:func:`provenance_validation.validate_provenance` instead — that is the
only place that performs actual C2PA validation.

Semantic corrections vs. the earlier version (see task requirements):

* The mere presence of ``c2pa``, ``claim_generator``, or
  ``created_software_agent`` no longer sets ``has_ai_claim``. Those tag
  names identify software that produced provenance information; they do
  not by themselves mean the image was AI-generated.
* ``has_c2pa`` was renamed ``has_c2pa_marker`` to make its
  "raw indicator, not validation" meaning explicit. It carries no score
  weight — validated provenance is exposed separately on
  :class:`ProvenanceResult`.
* Provider keywords (openai, midjourney, firefly, …) still contribute
  to the heuristic score but are tagged as ``unverified_ai_provider_hints``
  in the surfaced features so downstream consumers see them as such.
* Missing metadata remains a neutral 0.5 (uncertain) — never "real".
"""

